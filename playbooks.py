def playbooks_for(product_model: str):
    return PHONE_PLAYBOOKS if is_phone(product_model) else PLAYBOOKS

PLATFORM_BRIEFS = {
    "朋友圈": "写成导购愿意发给熟人的短消息，正文目标90至180字，一个核心事实。不要单独写口号式标题，不用话题标签。各字段应自然连读，不重复开头。",
    "小红书": "标题围绕具体选购问题，避免必看、闭眼入、天花板。正文目标250至450字，短段落，少量精准标签，不堆表情。",
    "公众号": "写成门店选型专栏，正文目标500至800字，有问题、核对依据和适用限制，用简洁小标题串起来，避免官宣新闻稿。",
}


def store_task(product_model: str, audience: str, scene: str, platform: str, angle: str) -> Task:
    book = playbooks_for(product_model)[audience]
    if scene not in book["scenes"]:
        raise ValueError("场景不属于当前客群。")
    brief = "\n".join([book["brief"], ANGLES[angle], PLATFORM_BRIEFS[platform],
                       "选购问题示意（不可机械照抄）：" + book["question"], book["check"],
                       "场景与表达参考不是产品事实，不授权任何参数、功能、价格和销售承诺。"])
    return Task(product_model=product_model, audience=audience, scenario=scene, platform=platform,
                writing_brief=brief)
